const alphabet = ['A', 'B', 'C', 'D'];

function initQuiz() {
    const container = document.getElementById('quizContainer');
    
    quizData.forEach((item, index) => {
        const questionCard = document.createElement('div');
        questionCard.className = 'bg-white p-6 rounded-xl shadow-sm border border-gray-200 mb-6';
        
        let optionsHtml = '';
        item.options.forEach((opt, optIndex) => {
            optionsHtml += `
                <div class="mb-3">
                    <label id="label-${index}-${optIndex}" class="option-label flex items-start p-4 border border-gray-200 rounded-lg cursor-pointer">
                        <input type="radio" name="question-${index}" value="${optIndex}" class="mt-1 mr-3 w-4 h-4 text-blue-600 focus:ring-blue-500" onclick="checkAnswer(${index}, ${optIndex})">
                        <span class="font-bold mr-2">${alphabet[optIndex]}.</span> 
                        <span class="text-gray-700 leading-relaxed">${opt}</span>
                    </label>
                </div>
            `;
        });

        questionCard.innerHTML = `
            <h3 class="text-lg font-bold text-gray-900 mb-4">${item.q}</h3>
            <div id="options-${index}">${optionsHtml}</div>
            <div id="feedback-${index}" class="mt-3 font-semibold text-lg hidden"></div>
        `;
        container.appendChild(questionCard);
    });
}

function checkAnswer(qIndex, selectedIndex) {
    const correctIndex = quizData[qIndex].answer;
    const isCorrect = (selectedIndex === correctIndex);
    
    // Disable all options for this question
    const radios = document.getElementsByName(`question-${qIndex}`);
    radios.forEach(r => r.disabled = true);
    
    // Update labels styles
    for(let i=0; i<4; i++) {
        const label = document.getElementById(`label-${qIndex}-${i}`);
        if(label) {
            label.classList.add('disabled');
            label.style.pointerEvents = 'none'; // Prevent further clicks
            
            if(i === correctIndex) {
                label.classList.add('correct');
            } else if (i === selectedIndex && !isCorrect) {
                label.classList.add('wrong');
            }
        }
    }
    
    // Show feedback message
    const feedback = document.getElementById(`feedback-${qIndex}`);
    feedback.classList.remove('hidden');
    if(isCorrect) {
        feedback.innerText = '✅ Chính xác!';
        feedback.classList.add('text-green-600');
    } else {
        feedback.innerText = '❌ Sai rồi! Đáp án đúng là ' + alphabet[correctIndex];
        feedback.classList.add('text-red-600');
    }
}

